export function getRoomType(room){
  const key = String(room || "").trim().toUpperCase();
  return ROOM_TYPE_BY_ROOM[key] || "";
}

export function getChecklistTemplate(roomType){
  const src = CHECKLIST_TEMPLATE_BY_TYPE[roomType] || [];
  return src.map((x, index) => ({
    row_no: index + 1,
    area: x.area || "",
    utility: x.utility || "",
    condition: String(x.condition || "NORMAL").toUpperCase() === "DEFECT" ? "DEFECT" : "NORMAL",
    notes: x.notes || "",
    update_smarthome: !!x.update_smarthome
  }));
}
